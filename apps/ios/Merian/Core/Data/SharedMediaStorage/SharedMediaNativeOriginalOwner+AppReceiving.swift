    }
    func recoverAppReleasePair(_ progress: SharedMediaNativeReceivingReleaseValues.Progress) async throws -> SharedMediaNativeReceivingReleaseValues.Progress {
        let plan = progress.plan
        return try await withReceivingLocks(queueID: plan.queueID.uuidString, observationID: plan.observationID.uuidString) { lock in
            try await self.appReleaseStageWorkflow(lock: lock) { try $0.reconcilePair(progress) }
        }
    }
    /// Uses retained IDs only, and returns typed saved evidence without inventing
    /// the consumed stage header. The supplied Prepared is descriptive, not authority.
    func discoverAppRelease(_ prepared: SharedMediaNativeReceivingIntent.Prepared) async throws -> SharedMediaNativeAppReleaseStageOperations.Saved? {
        try await withReceivingLocks(queueID: prepared.queueID.uuidString, observationID: prepared.observationID.uuidString) { lock in
            try await self.appReleaseStageWorkflow(lock: lock) { try $0.discover(prepared: prepared) }
        }
    }
    func executeAppRecovery(_ action: SharedMediaNativeRecoveryAction, storage: SharedMediaNativeStorageRepository,
                            grant: SharedMediaNativeAppDispatchGrant) async throws -> SharedMediaNativeRecoveryAction.Result {
        let prepared = try await action.target(storage: storage, grant: grant)
        return try await withReceivingLocks(queueID: prepared.queueID.uuidString, observationID: prepared.observationID.uuidString) { lock in
            try action.validateTarget(prepared, storage: storage, grant: grant)
            let result = try await action.perform(storage.appRecoveryPresentation(grant: grant, lock: lock), prepared: prepared)
            try action.validateTarget(prepared, storage: storage, grant: grant)
            return result
        }
    }
    func executeLockedAppRecovery(_ action: SharedMediaNativeRecoveryAction) async throws -> SharedMediaNativeRecoveryAction.Result {
        let prepared = try action.selectFixedTarget()
        return try await withReceivingLocks(queueID: prepared.queueID.uuidString, observationID: prepared.observationID.uuidString) { lock in
            try await self.performLockedAppRecovery(action, lock: lock, prepared: prepared)
        }
    }
    func verifiedAppInitialApplication(_ prepared: SharedMediaNativeReceivingIntent.Prepared,
                                       readOriginal: @escaping @MainActor (InitialCompletionDocuments.CpmAdmission, @escaping @MainActor @Sendable () throws -> Void) async throws -> InitialCompletionDocuments.CpmAcquisition?) async throws -> NativeVerifiedInitialApplication? {
        let applied = try await withReceivingLocks(queueID: prepared.queueID.uuidString, observationID: prepared.observationID.uuidString) { lock in
            try await self.appPhotoAllocationWorkflow(lock: lock) { try await $0().initialApplication().apply(prepared, readOriginal: readOriginal) }
        }
        return applied.map { .init(owner: self, prepared: prepared, cohort: $0) }
    }
    func withReceivingLocks<T: Sendable>(queueID: String, observationID: String,
                                         body: @MainActor (SharedMediaNativeReceivingLockGrant) async throws -> T) async throws -> T {
        let coordinator = ScanInferencePersistenceCoordinator.shared
        let held = await coordinator.acquireAll(scanIds: [queueID, observationID])
        let lock = SharedMediaNativeReceivingLockGrant()
        do {
            try Task.checkCancellation()
            // appReceivingWorkflow immediately checks the current account/owner
            // and acquires its work lease before any repository read or mutation.
            let value = try await body(lock)
            lock.close()
            await coordinator.releaseAll(scanIds: held)
            return value
        } catch {
            lock.close()
            await coordinator.releaseAll(scanIds: held)
            throw error
        }
    }
}

/// Minted only after both canonical coordinator locks are held; never survives
/// lock release and never escapes the lock-owning wrapper's private closure.
@MainActor
final class SharedMediaNativeReceivingLockGrant {
    private var active = true
    fileprivate init() {}
    fileprivate func close() { active = false }
    func validate() throws {
        try Task.checkCancellation()
        guard active else { throw SharedMediaStorageFailure.closed }
    }
}

/// Only the lock-owning native owner generates fresh submission identities.
/// Existing discovery supplies the exact immutable IDs instead of new ones.
struct SharedMediaNativeReceivingStageIdentity: Sendable {
    let operationID: UUID, queueID: UUID, observationID: UUID, bindingID: UUID, generation: UUID, eventID: UUID
    let timestamp: Date
    let savedBytes: Data?
    fileprivate init(saved: SharedMediaNativeReceivingIntent.Prepared?) throws {
        if let saved {
            operationID = saved.operationID; queueID = saved.queueID; observationID = saved.observationID
            bindingID = saved.bindingID; generation = saved.generation; eventID = saved.eventID
            timestamp = Date(timeIntervalSinceReferenceDate: Double(bitPattern: saved.timestampBits))
            savedBytes = try saved.encoded()
        } else {
            operationID = UUID(); queueID = UUID(); observationID = UUID(); bindingID = UUID()
            generation = UUID(); eventID = UUID(); timestamp = Date(); savedBytes = nil
        }
    }
}

/// Descriptive identity selection occurs before its coordinator locks; the
/// complete observed slot must still match under those locks before any save.
struct NativeReceivingRestageIdentity: Sendable {
    let observed: SharedMediaNativeReceivingIntentGraph.Row
    let predecessor: SharedMediaNativeReceivingIntent.Abandoned
    let identity: SharedMediaNativeReceivingStageIdentity
    let savedSuccessor: SharedMediaNativeReceivingIntent.Prepared?
    fileprivate init(observed: SharedMediaNativeReceivingIntentGraph.Row,
                     predecessor: SharedMediaNativeReceivingIntent.Abandoned) throws {
        self.observed = observed; self.predecessor = predecessor
        let slot = try SharedMediaNativeReceivingSlot.decode(observed, profile: predecessor.profile)
        switch slot {
        case .abandoned(let saved):
            guard try saved.encoded() == predecessor.encoded() else { throw SharedMediaStorageFailure.stale }
            identity = try .init(saved: nil); savedSuccessor = nil
        case .prepared(let prepared):
            guard prepared.version == 2, prepared.package.id == predecessor.package.id,
                  prepared.intentRevision == (try SharedMediaStoragePolicy.add(predecessor.revision, 1)),
                  prepared.restagedFromSHA256 == (try SharedMediaAcquisitionEncoding.digest(predecessor.encoded())) else {
                throw SharedMediaStorageFailure.stale
            }
            identity = try .init(saved: prepared); savedSuccessor = prepared
        case .received: throw SharedMediaStorageFailure.closed
        }
        guard Set([identity.operationID, identity.queueID, identity.observationID, identity.bindingID, identity.generation, identity.eventID])
            .isDisjoint(with: [predecessor.operationID, predecessor.queueID, predecessor.observationID, predecessor.bindingID,
                              predecessor.generation, predecessor.eventID]) else { throw SharedMediaStorageFailure.conflict }
    }
}

@MainActor
extension SharedMediaNativeOriginalOwner {
    func restageAppReceiving(_ predecessor: SharedMediaNativeReceivingIntent.Abandoned,
                             draftGeneration: UUID, pairIDs: [UUID]) async throws -> SharedMediaNativeReceivingIntent.Prepared {
        guard let row = try await discoverAppReceivingSlot(packageID: predecessor.package.id) else {
            throw SharedMediaStorageFailure.stale
        }
        let identity = try NativeReceivingRestageIdentity(observed: row, predecessor: predecessor)
        return try await withReceivingLocks(queueID: identity.identity.queueID.uuidString,
                                            observationID: identity.identity.observationID.uuidString) { lock in
            try await self.appReceivingWorkflow(lock: lock) {
                try await $0.restage(identity, draftGeneration: draftGeneration, pairIDs: pairIDs)
            }
        }
    }
}

