import { join } from "node:path";
import { functionsRoot } from "./function_dependency_tools.ts";
import { computeFunctionBundleDigests } from "./function_bundle_identity.ts";
import { GEMINI_DEPLOYMENT_IDENTITIES } from "../functions/_shared/geminiDeploymentIdentity.ts";
export const GEMINI_FUNCTION_NAMES = Object.freeze(
  Object.keys(GEMINI_DEPLOYMENT_IDENTITIES).sort(),
);
const path = join(functionsRoot, "_shared", "geminiDeploymentIdentity.ts");
export async function computeGeminiBundleDigests() {
  return await computeFunctionBundleDigests(GEMINI_FUNCTION_NAMES, path);
}
if (import.meta.main) {
  const digests = await computeGeminiBundleDigests();
  const source =
    `// GENERATED by generate_gemini_deployment_identity.ts. All generated digest payloads are excluded.\nexport const GEMINI_DEPLOYMENT_IDENTITIES = Object.freeze(${
      JSON.stringify(digests, null, 2)
    } as const);\n`;
  const formatted = await new Deno.Command(Deno.execPath(), {
    args: ["fmt", "--ext=ts", "-"],
    stdin: "piped",
    stdout: "piped",
    stderr: "null",
  }).spawn();
  const writer = formatted.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();
  const output = await formatted.output();
  if (!output.success) throw new Error("gemini_identity_format_failed");
  const expected = new TextDecoder().decode(output.stdout);
  if (Deno.args.includes("--write")) await Deno.writeTextFile(path, expected);
  else if (Deno.args.includes("--check")) {
    if (await Deno.readTextFile(path) !== expected) {
      throw new Error("gemini_identity_stale");
    }
  } else console.log(JSON.stringify(digests));
}
