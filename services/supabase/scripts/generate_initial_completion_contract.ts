/** Private completion structural rules for the native consumer. No route/DTO grant. */
import schema from "../functions/_shared/initialAnalysis/completion-schema-v1.json" with {
  type: "json",
};
import statusResponse from "../functions/_shared/initialAnalysis/completion-status-response-schema-v1.json" with {
  type: "json",
};
import { initialCanonicalText } from "../functions/_shared/initialAnalysis/canonical.ts";
import { completionVectors } from "./initial_completion_vectors.ts";
import { initialCompletionAdmissionKeys } from "../functions/_shared/initialAnalysis/completionAcquisition.ts";
import acknowledgement from "../functions/_shared/initialAnalysis/cpm-completion-admission-schema-v1.json" with {
  type: "json",
};

import {
  dataContractV2,
  provenanceContractV2,
} from "../functions/_shared/initialAnalysis/resultSchemaV2.ts";

/** Trusted generated rules use JSON, not the bounded IC-1 payload grammar:
 * contract metadata has camel-case keys and deeper schema nesting. */
export function retainedResultSwiftSchema(): string {
  const text = JSON.stringify({
    data: dataContractV2,
    provenance: provenanceContractV2,
  });
  if (text.includes('"###')) {
    throw new Error("retained_result_schema_delimiter");
  }
  return `// Generated by services/supabase/scripts/generate_initial_completion_contract.ts.
// Frozen private resultSchemaV2.ts; never regenerate from the live Identify contract.
enum InitialRetainedResultSchema {
    static let json = ###"${text}"###
}
`;
}
export const retainedResultSwiftPath = new URL(
  "../../../apps/ios/Merian/Core/Network/Inference/InitialRetainedResultSchema.swift",
  import.meta.url,
);

export function completionSwiftSchema(): string {
  const text = initialCanonicalText({
    ...schema,
    admission: {
      type: "object",
      properties: Object.fromEntries(
        initialCompletionAdmissionKeys.map((
          key,
        ) => [key, schema.receipt.properties[key]]),
      ),
    },
    cpm_admission_acknowledgement: acknowledgement,
    status_response: statusResponse,
  });
  if (text.includes('"###')) throw new Error("completion_schema_delimiter");
  return `// Generated by services/supabase/scripts/generate_initial_completion_contract.ts.
// Sources: completion-schema-v1.json, cpm-completion-admission-schema-v1.json,
// completion-status-response-schema-v1.json and completionAcquisition.ts admission keys. Do not edit.
enum InitialCompletionSchema {
    static let canonical = ###"${text}"###
}
`;
}

export const completionSwiftPath = new URL(
  "../../../apps/ios/Merian/Core/Network/Inference/InitialCompletionSchema.swift",
  import.meta.url,
);
export const completionFixturePath = new URL(
  "../../../apps/ios/TestSupport/InitialCompletionFixtures.json",
  import.meta.url,
);
if (import.meta.main) {
  if (
    Deno.args.length !== 1 || !["--write", "--check"].includes(Deno.args[0])
  ) {
    throw new Error("expected --write or --check");
  }
  for (
    const [path, expected] of [
      [completionSwiftPath, completionSwiftSchema()],
      [retainedResultSwiftPath, retainedResultSwiftSchema()],
      [
        completionFixturePath,
        JSON.stringify(await completionVectors(), null, 2) + "\n",
      ],
    ] as const
  ) {
    if (Deno.args[0] === "--write") {
      await Deno.writeTextFile(path, expected);
    } else if (await Deno.readTextFile(path) !== expected) {
      throw new Error("initial_completion_swift_contract_drift");
    }
  }
}
